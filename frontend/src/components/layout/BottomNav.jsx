export function BottomNav() {
  const { isAuthenticated, isAdmin } = useAuth();

  if (!isAuthenticated) return null;

  const navItems = [
    { to: '/', label: 'Home', iconName: 'Home' },
    { to: '/invoices', label: 'Invoices', iconName: 'Invoices' },
    { to: '/purchases', label: 'Purchases', iconName: 'Purchases' },
    { to: '/expenses', label: 'Expenses', iconName: 'Expenses' },
    ...(isAdmin ? [{ to: '/reports', label: 'Reports', iconName: 'Reports' }] : []),
    ...(isAdmin ? [{ to: '/staff', label: 'Staff', iconName: 'Staff' }] : [])
  ];

  return (
    <nav className="fixed bottom-0 left-0 right-0 bg-neutral-card border-t border-neutral-border z-40 h-[64px] pb-safe md:hidden rounded-t-[16px]">
      <div className="flex justify-around items-center h-[64px] px-1">
        {navItems.map((item) => (
          <NavLink
            key={item.to}
            to={item.to}
            end={item.to === '/'}
            className={({ isActive }) =>
              `flex flex-col items-center justify-center w-full h-full text-[11px] font-medium transition-all min-h-[44px] ${
                isActive ? 'text-brand-primary' : 'text-neutral-tertiary'
              }`
            }
          >
            {({ isActive }) => (
              <>
                <svg
                  xmlns="http://www.w3.org/2000/svg"
                  fill={isActive ? "currentColor" : "none"}
                  viewBox="0 0 24 24"
                  strokeWidth={isActive ? "0" : "1.5"}
                  stroke="currentColor"
                  className="w-[22px] h-[22px] mb-1"
                >
                  {isActive ? icons[item.iconName].solid : icons[item.iconName].outline}
                </svg>
                <span className="truncate max-w-[60px]">{item.label}</span>
              </>
            )}
          </NavLink>
        ))}
      </div>
    </nav>
  );
}

export default BottomNav;
